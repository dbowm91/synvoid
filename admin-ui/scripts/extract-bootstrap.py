#!/usr/bin/env python3
"""Extract trunk's inline WASM bootstrap to dist/bootstrap.js.

The admin server sends `script-src 'self'` with no `unsafe-inline`, so the
inline `<script type="module">` trunk emits into dist/index.html is refused
and the panel never starts. This post-build step moves that block verbatim
into dist/bootstrap.js and references it externally with an SRI hash.

Idempotent: if dist/index.html already references /bootstrap.js, the script
verifies the file exists and exits 0. Run via `npm run build` (which chains
it after `trunk build`), so committed dist/ always matches a fresh build
and the CI drift check stays green.
"""

import base64
import hashlib
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
DIST = HERE.parent / "dist"
INDEX = DIST / "index.html"
BOOTSTRAP = DIST / "bootstrap.js"

INLINE_RE = re.compile(
    r"<script type=\"module\">\n(.*?)\n</script>", re.DOTALL
)

COMMENT = """<!-- The WASM bootstrap must stay an external file: the admin server sends
     `script-src 'self'` with no 'unsafe-inline', so an inline bootstrap is
     refused and the panel never starts. Regenerated by
     `scripts/extract-bootstrap.py` from trunk's inline block. -->
"""


def main() -> int:
    html = INDEX.read_text()
    if 'src="/bootstrap.js"' in html:
        if not BOOTSTRAP.exists():
            print("index.html references /bootstrap.js but it is missing", file=sys.stderr)
            return 1
        print("bootstrap.js already extracted; nothing to do")
        return 0

    match = INLINE_RE.search(html)
    if not match:
        print("no inline <script type=\"module\"> block found in dist/index.html", file=sys.stderr)
        return 1

    body = match.group(1)
    BOOTSTRAP.write_text(body + "\n")

    digest = hashlib.sha384(BOOTSTRAP.read_bytes()).digest()
    integrity = "sha384-" + base64.b64encode(digest).decode()
    tag = (
        f'<script type="module" src="/bootstrap.js" '
        f'crossorigin="anonymous" integrity="{integrity}"></script>'
    )
    INDEX.write_text(html[: match.start()] + COMMENT + tag + html[match.end() :])
    print(f"extracted bootstrap.js ({BOOTSTRAP.stat().st_size} bytes, {integrity[:19]}...)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
